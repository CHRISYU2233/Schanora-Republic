async function call(method, pathname, body) {
  const res = await fetch(`${base}${pathname}`, {
    method,
    headers: body ? { 'Content-Type': 'application/json' } : undefined,
    body: body ? JSON.stringify(body) : undefined,
  });
  const json = await res.json().catch(() => null);
  if (!res.ok || !json || json.code !== 0) {
    throw new Error(`${method} ${pathname} → ${res.status} ${(json && json.message) || ''}`);
  }
  return json.data;
}

async function upload(kbId, fileName, text) {
  const fd = new FormData();
  fd.append('file', new Blob([text], { type: 'text/markdown' }), fileName);
  const res = await fetch(`${base}/api/v1/knowledge-bases/${encodeURIComponent(kbId)}/documents`, {
    method: 'POST',
    body: fd,
  });
  const json = await res.json().catch(() => null);
  if (!res.ok || !json || json.code !== 0) {
    throw new Error(`上传 ${fileName} → ${res.status} ${(json && json.message) || ''}`);
  }
  return json.data;
}

